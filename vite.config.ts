import { defineConfig, type Plugin } from 'vitest/config';
import react from '@vitejs/plugin-react';
import { fileURLToPath, URL } from 'node:url';

// Production site is served from https://icei.pucminas.br/cbsoft27/. Override
// with VITE_BASE (e.g. /2027/ for https://cbsoft.sbc.org.br/2027/, / for Vercel).
const base = process.env.VITE_BASE ?? '/cbsoft27/';

/* Apache (cbsoft.sbc.org.br) only serves files that exist, so reloading a
 * route like /2027/sbes/chamada gave a 404. This .htaccess sends every
 * unknown path back to index.html so React Router can render it. A missing
 * file under assets/ stays a real 404. The paths depend on the base, so the
 * file is generated at build time instead of living in public/. */
function apacheSpaFallback(): Plugin {
  return {
    name: 'apache-spa-fallback',
    apply: 'build',
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: '.htaccess',
        source: `# Generated by vite.config.ts: SPA fallback for Apache.
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase ${base}
  RewriteRule ^index\\.html$ - [L]
  RewriteCond %{REQUEST_URI} !^${base}assets/
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule . ${base}index.html [L]
</IfModule>
<IfModule !mod_rewrite.c>
  FallbackResource ${base}index.html
</IfModule>

# index.html is never cached, so new deploys show up right away.
<IfModule mod_headers.c>
  <Files "index.html">
    Header set Cache-Control "no-cache"
  </Files>
</IfModule>
`,
      });
    },
  };
}

export default defineConfig({
  base,
  plugins: [react(), apacheSpaFallback()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  test: {
    environment: 'jsdom',
    include: ['src/**/*.test.{ts,tsx}'],
    setupFiles: ['src/test/setup.ts'],
    // Full-App renders in jsdom sit around 2–5s each; give them headroom
    // so the suite doesn't flake on a loaded machine.
    testTimeout: 15000,
  },
});
